"""Model-quality evaluation, kept separate from policy enforcement.

Runs the nine notes through the real system (mock AI in normal mode) RUNS times,
then scores the AI's RAW output against evals/gold.json, and separately reports
what the server's policy did with it. Writes evals/results.md. Every number comes
from this run.

    docker compose run --rm tools python -m evals.run
"""

import json
import statistics
import sys
from pathlib import Path

from fastapi.testclient import TestClient

from safecounter import admin, config
from safecounter.scribe import evidence_in_note

RUNS = int(sys.argv[1]) if len(sys.argv) > 1 else 3
HERE = Path(__file__).parent
GOLD = {k: v for k, v in json.loads((HERE / "gold.json").read_text()).items() if not k.startswith("_")}
NOTES = {n["id"]: n for n in json.loads(config.NOTES_PATH.read_text())["notes"]}


def run_once(client):
    with admin.connect() as conn:
        admin.reset(conn)
    out = {}
    for nid, n in NOTES.items():
        body = {k: n[k] for k in ("id", "text", "written_at", "scope", "source")}
        r = client.post(f"/shops/{n['shop_id']}/notes", json=body,
                        headers={"Authorization": f"Bearer tok_{n['author_id'][2:]}"})
        out[nid] = r.json() if r.status_code == 200 else {"error": r.status_code}
    with admin.connect() as conn:
        raw = conn.execute("SELECT t.note_id, p.record_id, p.field, p.raw, p.status FROM proposals p "
                           "JOIN ai_tasks t ON t.id = p.task_id ORDER BY p.id").fetchall()
    return out, raw


def score(results, raw):
    m = {"proposals": 0, "correct": 0, "wrong_value": 0, "unsupported": 0, "gold": 0, "found": 0,
         "evidence_verbatim": 0, "abstain_expected": 0, "abstain_respected": 0,
         "wrong_reached_human": 0, "wrong_blocked": 0, "correct_blocked": 0, "schema_valid": 0, "notes": 0}
    detail = []
    for nid, gold in GOLD.items():
        m["notes"] += 1
        res = results[nid]
        if "error" in res:
            continue
        m["schema_valid"] += 1
        rows = [r for r in raw if r["note_id"] == nid]
        proposed = {}
        for r in rows:
            key = f"{r['record_id']}|{r['field']}"
            p = r["raw"] if isinstance(r["raw"], dict) else {}
            proposed[key] = p.get("value")
            m["proposals"] += 1
            if isinstance(p.get("evidence"), str) and evidence_in_note(p["evidence"], NOTES[nid]["text"]):
                m["evidence_verbatim"] += 1
            if key in gold["proposals"]:
                ok = gold["proposals"][key] is None or gold["proposals"][key] == p.get("value")
                verdict = "correct" if ok else "wrong_value"
            else:
                verdict = "unsupported"
            m["correct" if verdict == "correct" else verdict] += 1
            if verdict == "correct" and r["status"] == "blocked":
                m["correct_blocked"] += 1
            if verdict != "correct":
                m["wrong_reached_human" if r["status"] == "pending" else "wrong_blocked"] += 1
                detail.append(f"{nid} {key} = {p.get('value')!r}: {verdict}, server -> {r['status']}")
        m["gold"] += len(gold["proposals"])
        m["found"] += sum(1 for k, v in gold["proposals"].items() if k in proposed and (v is None or proposed[k] == v))
        m["abstain_expected"] += len(gold["abstain"])
        m["abstain_respected"] += sum(1 for k in gold["abstain"] if k not in proposed)
    return m, detail


def pct(a, b):
    return f"{100 * a / b:.0f}% ({a}/{b})" if b else "n/a"


def main():
    client = TestClient(__import__("safecounter.api", fromlist=["app"]).app)
    runs = [run_once(client) for _ in range(RUNS)]
    m, detail = score(*runs[0])
    latencies = [res.get("latency_ms", 0) for results, _ in runs for res in results.values() if "latency_ms" in res]
    signatures = [json.dumps(sorted((r["note_id"], r["record_id"], r["field"], json.dumps(r["raw"], sort_keys=True))
                                    for r in raw)) for _, raw in runs]
    consistent = len(set(signatures)) == 1

    lines = [
        "# Evaluation results", "",
        f"Generated by `python -m evals.run` against the mock AI in normal mode, {RUNS} runs of the nine notes.",
        "Gold labels: `evals/gold.json` (hand-written). The mock ignores the prompt, so these numbers measure",
        "the mock, not `prompts/scribe_v1.md`.", "",
        "## Model quality (raw AI output vs gold)", "",
        "| Metric | Result |", "| --- | --- |",
        f"| Precision: proposals that are correct | {pct(m['correct'], m['proposals'])} |",
        f"| Recall: gold changes found with the right value | {pct(m['found'], m['gold'])} |",
        f"| Wrong value for a supported field | {m['wrong_value']} |",
        f"| Proposals the note does not support | {m['unsupported']} |",
        f"| Evidence quoted word for word | {pct(m['evidence_verbatim'], m['proposals'])} |",
        f"| Abstention respected (unsupported fields not proposed) | {pct(m['abstain_respected'], m['abstain_expected'])} |",
        f"| Schema-valid responses | {pct(m['schema_valid'], m['notes'])} |",
        f"| Identical output across {RUNS} runs | {'yes' if consistent else 'NO'} |",
        f"| Latency per note (ms) | median {statistics.median(latencies):.0f}, max {max(latencies)} |", "",
        "## Policy outcome for the AI's mistakes", "",
        "| Metric | Result |", "| --- | --- |",
        f"| Wrong proposals blocked by the server | {pct(m['wrong_blocked'], m['wrong_blocked'] + m['wrong_reached_human'])} |",
        f"| Wrong proposals that reached a human as pending | {m['wrong_reached_human']} |",
        f"| Correct proposals blocked by the server (false blocks) | {m['correct_blocked']} |", "",
        "## Every AI mistake", "",
    ] + [f"- {d}" for d in detail] + [""]
    (HERE / "results.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
